// Copies the hand-written documents that live in the repository into the
// Starlight content directory, rewriting their links as it goes.
//
// The point is single sourcing (ADR-0027). ADRs are authored in docs/adr/ and
// contributors add files there; the PRD and the roadmap are read on GitHub as
// often as on the site; CONTRIBUTING is linked by GitHub's own pull request
// UI. None of them should acquire a second home, so the site generates its
// copies at build time. Everything written here is gitignored.

import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = resolve(siteDir, '..');
const outDir = join(siteDir, 'src/content/docs/project');

const BASE = '/redlines';
const GITHUB = 'https://github.com/houfu/redlines';
const BLOB = `${GITHUB}/blob/main`;

/** Where each source document ends up once it is a page. */
const pageFor = {
	'PRD.md': `${BASE}/project/prd/`,
	'ROADMAP.md': `${BASE}/project/roadmap/`,
	'CONTRIBUTING.md': `${BASE}/project/contributing/`,
	'README.md': `${BASE}/project/adr/`, // only ever linked as the ADR index
};

/** Documents that stay on GitHub rather than becoming pages. */
const stayOnGitHub = {
	'competitive-landscape-2026-08.md': `${BLOB}/docs/competitive-landscape-2026-08.md`,
	'Code_of_Conduct.md': `${BLOB}/Code_of_Conduct.md`,
};

const adrSlug = /^(\d{4})-([a-z0-9-]+)\.md$/;

/**
 * Rewrite one markdown link target. Relative links between repository files
 * are meaningless once the file is a page, and GitHub's bare `/issues` shorthand
 * is meaningless anywhere but github.com.
 */
function rewriteTarget(target) {
	if (/^(https?:|mailto:|#)/.test(target)) return target;

	// GitHub's repository-relative issue links.
	if (target.startsWith('/issues') || target.startsWith('issues')) {
		return `${GITHUB}/${target.replace(/^\/?/, '')}`;
	}

	const name = target.split('/').pop();
	if (!name) return target;

	const adr = name.match(adrSlug);
	if (adr) return `${BASE}/project/adr/${adr[1]}-${adr[2]}/`;
	if (stayOnGitHub[name]) return stayOnGitHub[name];
	if (pageFor[name]) return pageFor[name];

	return target;
}

const rewriteLinks = (text) =>
	text.replace(/\]\(([^)\s]+)\)/g, (whole, target) => `](${rewriteTarget(target)})`);

/** Starlight renders the title from frontmatter, so the H1 would be a duplicate. */
function splitTitle(text) {
	const match = text.match(/^#\s+(.+?)\s*$/m);
	if (!match) return { title: null, body: text };
	return { title: match[1], body: text.slice(0, match.index) + text.slice(match.index + match[0].length) };
}

const quote = (s) => `"${s.replace(/"/g, '\\"')}"`;

async function emit(path, { title, label, order, description, body, source }) {
	const frontmatter = [
		'---',
		`title: ${quote(title)}`,
		description ? `description: ${quote(description)}` : null,
		'sidebar:',
		label ? `  label: ${quote(label)}` : null,
		order != null ? `  order: ${order}` : null,
		'---',
		'',
		`<!-- Generated by scripts/sync-docs.mjs from ${source}. Edit that file, not this one. -->`,
		'',
	]
		.filter((line) => line !== null)
		.join('\n');
	await writeFile(path, frontmatter + rewriteLinks(body).trimStart() + '\n');
}

async function main() {
	await rm(outDir, { recursive: true, force: true });
	await mkdir(join(outDir, 'adr'), { recursive: true });

	// The ADRs, and their hand-written index as the section landing page.
	const adrDir = join(repoDir, 'docs/adr');
	for (const file of (await readdir(adrDir)).sort()) {
		if (!file.endsWith('.md')) continue;
		const raw = await readFile(join(adrDir, file), 'utf8');
		const { title, body } = splitTitle(raw);
		const source = `docs/adr/${file}`;

		if (file === 'README.md') {
			await emit(join(outDir, 'adr/index.md'), {
				title: title ?? 'Architecture decision records',
				label: 'Overview',
				order: 0,
				description: 'Why each design decision was made, what was rejected, and when to revisit it.',
				body,
				source,
			});
			continue;
		}

		const match = file.match(adrSlug);
		if (!match) continue;
		const [, number, slug] = match;
		const short = (title ?? file).replace(/^ADR-\d+:\s*/, '');
		await emit(join(outDir, `adr/${number}-${slug}.md`), {
			title: title ?? file,
			label: `${number} · ${short.length > 44 ? short.slice(0, 43).trimEnd() + '…' : short}`,
			order: Number(number),
			body,
			source,
		});
	}

	// The planning documents. The competitive landscape stays on GitHub: it is
	// a dated research note, not documentation.
	const plans = [
		{
			file: 'docs/PRD.md',
			out: 'prd.md',
			label: 'PRD',
			order: 1,
			description: 'What redlines 1.0 is, who it is for, and what it must do.',
		},
		{
			file: 'ROADMAP.md',
			out: 'roadmap.md',
			label: 'Roadmap',
			order: 2,
			description: 'Which release each feature lands in.',
		},
		{
			file: 'CONTRIBUTING.md',
			out: 'contributing.md',
			label: 'Contributing',
			order: 3,
			description: 'How to report a bug, propose a change, and build the documentation.',
		},
	];

	for (const plan of plans) {
		const raw = await readFile(join(repoDir, plan.file), 'utf8');
		const { title, body } = splitTitle(raw);
		await emit(join(outDir, plan.out), {
			title: title ?? plan.label,
			label: plan.label,
			order: plan.order,
			description: plan.description,
			body,
			source: plan.file,
		});
	}

	console.log(`synced repository documents into ${outDir.replace(siteDir + '/', '')}`);
}

await main();
